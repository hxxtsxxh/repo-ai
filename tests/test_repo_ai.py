def test_path_is_secretlike():
    assert path_is_secretlike(".env", DEFAULT_SECRET_PATH_GLOBS)
    assert path_is_secretlike("certs/server.pem", DEFAULT_SECRET_PATH_GLOBS)
    assert path_is_secretlike("config/credentials.json", DEFAULT_SECRET_PATH_GLOBS)
    assert not path_is_secretlike(".env.example", DEFAULT_SECRET_PATH_GLOBS)
    assert not path_is_secretlike("src/environment.ts", DEFAULT_SECRET_PATH_GLOBS)


@pytest.mark.parametrize("line,rule", [
    ('AWS_KEY = "AKIA4Z7QWMTPX9RLKD2N"', "aws-access-key-id"),
    ("token = 'ghp_016C7e42F292c6912E7710c838347Ae178B4a'", "github-token"),
    ('key = "sk-ant-api03-abcdefghijklmnop1234567890"', "anthropic-key"),
    ("-----BEGIN RSA PRIVATE KEY-----", "private-key-block"),
    ('DB = "postgres://svc:Xq7X2mVpLd93RtZbNw81@prod-db.example.net:5432/app"',
     "connection-string"),
])
def test_secret_rules_fire(line: str, rule: str):
    hits = scan_text("config/settings.py", line)
    assert any(h.rule == rule for h in hits), f"{rule} did not fire on {line!r}"


def test_documented_vendor_examples_are_suppressed():
    """AWS publishes AKIAIOSFODNN7EXAMPLE in its own docs; flagging it is noise."""
    assert not scan_text("README.md", 'AWS_KEY = "AKIAIOSFODNN7EXAMPLE"')


def test_secret_values_are_never_stored():
    secret = "AKIA4Z7QWMTPX9RLKD2N"
    hits = scan_text("app.py", f'AWS_KEY = "{secret}"')
    assert hits
    for hit in hits:
        assert secret not in hit.redacted
        assert hit.redacted.startswith(secret[:4])


def test_local_dev_connection_strings_are_not_flagged():
    """Every docker-compose file on earth has one of these. Flagging them
    trains people to ignore the report."""
    for line in (
        "DATABASE_URL: postgresql://galaxium:local_dev_password@postgres:5432/booking",
        "DATABASE_URL=postgres://user:pass@localhost/db",
        "REDIS_URL=redis://:devpassword@redis:6379/0",
    ):
        assert not scan_text("docker-compose.yml", line), f"false positive on {line!r}"


def test_compose_file_stays_indexed(repo: Path, cfg: Config):
    """Quarantine is reserved for key material; losing compose files would
    cost more architectural context than it protects."""
    (repo / "docker-compose.yml").write_text(
        "services:\n  db:\n    environment:\n"
        "      DATABASE_URL: postgres://app:local_dev_password@db:5432/app\n",
        encoding="utf-8")
    result = scan(repo, cfg)
    assert "docker-compose.yml" in {f.path for f in result.files}


def test_placeholders_do_not_fire():
    for line in (
        'API_KEY = "your-api-key-here"',
        'password = "changeme"',
        'token = os.environ["TOKEN"]',
        'SECRET = "${VAULT_SECRET}"',
        'api_key = "xxxxxxxxxxxxxxxxxxxxx"',
    ):
        assert not scan_text("app.py", line), f"false positive on {line!r}"


def test_entropy():
    assert shannon_entropy("aaaaaaaa") < 1.0
    assert shannon_entropy("Xk9$mQ2pLw7ZaB4c") > 3.5


