def _run_cli(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "repo_ai", *args, "-C", str(repo)],
        capture_output=True, text=True, encoding="utf-8", check=False,
    )


def test_cli_init_creates_everything(repo: Path):
    proc = _run_cli(repo, "init")
    assert proc.returncode == 0, proc.stderr

    for name in ("PROJECT_OVERVIEW.md", "ARCHITECTURE.md", "REPOSITORY_MAP.md",
                 "DEPENDENCIES.md", "TESTING.md", "CONVENTIONS.md",
                 "SECURITY_NOTES.md", "CONTEXT_INDEX.md", "NOTES.md", "facts.json"):
        assert (repo / ".bob" / "context" / name).is_file(), f"missing {name}"

    assert (repo / "AGENTS.md").is_file()
    assert (repo / ".bob" / "skills" / "repository-context" / "SKILL.md").is_file()
    assert (repo / ".bob" / "hooks" / "user-prompt.sh").is_file()
    assert (repo / ".bob" / "settings.json").is_file()
    assert (repo / ".bobignore").is_file()

    settings = json.loads((repo / ".bob" / "settings.json").read_text())
    assert "UserPromptSubmit" in settings["hooks"]
    assert "SessionStart" in settings["hooks"]


