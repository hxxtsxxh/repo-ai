def test_scan_excludes_noise(repo: Path, cfg: Config):
    result = scan(repo, cfg)
    paths = {f.path for f in result.files}

    assert "app/main.py" in paths
    assert "web/src/api.ts" in paths
    assert "README.md" in paths

    assert not any(p.startswith("node_modules/") for p in paths), "node_modules leaked"
    assert not any(p.startswith("dist/") for p in paths), "gitignored dist leaked"
    assert not any(p.startswith("build/") for p in paths), "gitignored build leaked"
    assert "debug.log" not in paths, "gitignored *.log leaked"
    assert ".env" not in paths, "SECRET FILE LEAKED INTO THE INDEX"


def test_env_example_is_indexed_but_env_is_not(repo: Path, cfg: Config):
    result = scan(repo, cfg)
    paths = {f.path for f in result.files}
    assert ".env.example" in paths
    assert ".env" not in paths
    assert ".env" in result.quarantined


def test_generated_files_are_marked_not_dropped(repo: Path, cfg: Config):
    result = scan(repo, cfg)
    generated = [f for f in result.files if f.role == "generated"]
    assert any("schema_pb2" in f.path for f in generated)


def test_scan_is_deterministic(repo: Path, cfg: Config):
    first = [f.path for f in scan(repo, cfg).files]
    second = [f.path for f in scan(repo, cfg).files]
    assert first == second == sorted(first)


