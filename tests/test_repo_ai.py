def _build_index(repo: Path, cfg: Config):
    from repo_ai.analyze import run_analysis
    context_dir = repo / cfg.out_dir
    run_analysis(repo, cfg, context_dir, incremental=False)
    return open_index(context_dir)


def test_retrieval_ranks_auth_files_first(repo: Path, cfg: Config):
    index = _build_index(repo, cfg)
    try:
        _, hits = retrieve(index, "fix the bug where login fails for existing users",
                           max_files=8)
        paths = [h.path for h in hits]
        assert paths, "retrieval returned nothing"
        assert "app/auth.py" in paths[:4], f"auth.py not ranked highly: {paths}"
        assert not any(p.startswith("node_modules") for p in paths)
        assert ".env" not in paths
    finally:
        index.close()


def test_retrieval_named_symbol_gives_line_ranges(repo: Path, cfg: Config):
    index = _build_index(repo, cfg)
    try:
        _, hits = retrieve(index, "change how authenticate_user signs the token", max_files=6)
        target = next((h for h in hits if h.path == "app/auth.py"), None)
        assert target is not None
        assert target.lines, "no line ranges for a symbol-named query"
        start, end, label = target.lines[0]
        assert start >= 1 and end >= start
        assert "authenticate_user" in label
    finally:
        index.close()


def test_retrieval_ci_query_prefers_workflow(repo: Path, cfg: Config):
    index = _build_index(repo, cfg)
    try:
        _, hits = retrieve(index, "the CI pipeline github actions workflow keeps failing",
                           max_files=6)
        paths = [h.path for h in hits]
        assert any(".github/workflows" in p or p == "Dockerfile" for p in paths), paths
    finally:
        index.close()


def test_retrieval_never_returns_quarantined(repo: Path, cfg: Config):
    index = _build_index(repo, cfg)
    try:
        for prompt in ("what is the database connection string",
                       "read the env file", "show me DATABASE_URL"):
            _, hits = retrieve(index, prompt, max_files=15)
            assert all(h.path != ".env" for h in hits), f"leaked .env for {prompt!r}"
    finally:
        index.close()


