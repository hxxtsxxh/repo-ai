def test_incremental_update_detects_change(repo: Path, cfg: Config):
    from repo_ai.analyze import run_analysis
    context_dir = repo / cfg.out_dir
    run_analysis(repo, cfg, context_dir, incremental=False)

    (repo / "app" / "billing.py").write_text(
        "def charge(amount: int) -> bool:\n    return True\n", encoding="utf-8")
    second = run_analysis(repo, cfg, context_dir, incremental=True)

    assert "app/billing.py" in second.changed
    assert len(second.changed) <= 4, f"too much re-parsed: {second.changed}"

    index = open_index(context_dir)
    try:
        assert index.find_symbol("charge")
    finally:
        index.close()


def test_incremental_update_handles_deletion(repo: Path, cfg: Config):
    from repo_ai.analyze import run_analysis
    context_dir = repo / cfg.out_dir
    run_analysis(repo, cfg, context_dir, incremental=False)
    (repo / "app" / "models.py").unlink()
    result = run_analysis(repo, cfg, context_dir, incremental=True)
    assert "app/models.py" in result.removed

    index = open_index(context_dir)
    try:
        assert index.get_file("app/models.py") is None
    finally:
        index.close()


