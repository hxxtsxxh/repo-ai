def render_overview(facts: RepoFacts) -> str:
    langs = list(facts.languages.items())
    total = sum(facts.languages.values()) or 1
    lang_rows = [
        [lang, _fmt_int(loc), f"{loc / total * 100:4.1f}%", _bar(loc / total)]
        for lang, loc in langs[:10]
    ]

    comp_rows = [
        [c.name, f"`{c.root}`", c.kind, ", ".join(c.languages[:3]) or "—",
         _fmt_int(c.loc), c.entrypoints[0] if c.entrypoints else "—"]
        for c in facts.components[:15]
    ]

    intro = ""
    for doc in facts.docs:
        if doc.get("category") == "readme" and doc.get("intro"):
            intro = doc["intro"]
            break

    cmd_lines = []
    for kind in ("install", "build", "run", "test", "lint", "db", "deploy"):
        for cmd in facts.commands.get(kind, [])[:3]:
            cmd_lines.append(f"| {kind} | `{cmd}` |")

    parts = [
        banner(facts),
        f"# {facts.name} — project overview",
        "",
        f"> {intro}" if intro else "> _No README summary found._",
        "",
        "## At a glance",
        "",
        _table(["Fact", "Value"], [
            ["Primary languages", ", ".join(lang for lang, _ in langs[:4]) or "unknown"],
            ["Lines of code (indexed)", _fmt_int(facts.total_loc)],
            ["Indexed files", f"{_fmt_int(facts.indexed_files)} of "
                             f"{_fmt_int(facts.total_files_seen)} seen"],
            ["Components", str(len(facts.components))],
            ["Package managers", ", ".join(facts.package_managers) or "none detected"],
            ["Frameworks", ", ".join(facts.frameworks[:12]) or "none detected"],
            ["External services", ", ".join(facts.external_services) or "none detected"],
            ["HTTP routes found", str(len(facts.routes))],
            ["Test suites", str(len(facts.test_suites))],
            ["Git", f"`{facts.git_branch}` @ `{facts.git_head}`"
                    if facts.git_head else "not a git repository"],
            ["Generated", facts.generated_at],
        ]),
        "",
        "## Languages",
        "",
        _table(["Language", "LOC", "Share", ""], lang_rows),
        "",
        "## Components",
        "",
        "A component is a directory with its own package manifest, or a "
        "top-level source directory in a repo without per-package manifests. "
        "Treat each as an independently buildable unit.",
        "",
        _table(["Component", "Root", "Kind", "Languages", "LOC", "Entrypoint"], comp_rows),
        "",
        "## Commands",
        "",
        "Extracted from manifests, Makefiles, and README code blocks. "
        "Verify before relying on them in automation.",
        "",
    ]
    if cmd_lines:
        parts.extend(["| Kind | Command |", "|---|---|", *cmd_lines])
    else:
        parts.append("_No commands detected. Check the README manually._")

    if facts.warnings:
        parts.extend(["", "## Analysis warnings", ""])
        parts.extend(f"- {w}" for w in facts.warnings)

    return "\n".join(parts) + "\n"


def render_architecture(facts: RepoFacts) -> str:
    layers: dict[str, list[str]] = facts.conventions.get("layers", {})  # type: ignore[assignment]
    order = ["frontend", "fullstack", "backend", "api", "auth", "data", "database",
             "cache", "search", "messaging", "async", "ml", "cloud", "infra", "ci",
             "build", "test", "realtime"]

    layer_rows = [
        [layer, ", ".join(sorted(layers[layer]))]
        for layer in order if layers.get(layer)
    ]
    for layer, values in sorted(layers.items()):
        if layer not in order and values:
            layer_rows.append([layer, ", ".join(sorted(values))])

    comp_kinds: dict[str, list[str]] = defaultdict(list)
    for comp in facts.components:
        comp_kinds[comp.kind].append(f"{comp.name} (`{comp.root}`)")

    mermaid = ["```mermaid", "graph TD"]
    seen_nodes: set[str] = set()

    def node_id(name: str) -> str:
        ident = "".join(ch if ch.isalnum() else "_" for ch in name)[:24]
        return ident or "n"

    for kind in ("app", "service", "library", "infra", "tooling", "docs"):
        for comp in facts.components:
            if comp.kind != kind:
                continue
            nid = node_id(comp.root)
            if nid in seen_nodes:
                continue
            seen_nodes.add(nid)
            shape = {"app": ('["', '"]'), "service": ('("', '")'),
                     "library": ('["', '"]'), "infra": ('{{"', '"}}'),
                     "tooling": ('["', '"]'), "docs": ('["', '"]')}[kind]
            mermaid.append(f"  {nid}{shape[0]}{comp.name}<br/>{kind}{shape[1]}")
    if layers.get("database") or layers.get("data"):
        stores = sorted(set(layers.get("database", []) + layers.get("data", [])))[:4]
        for store in stores:
            sid = node_id("db_" + store)
            mermaid.append(f'  {sid}[("{store}")]')
    for service in facts.external_services[:6]:
        sid = node_id("ext_" + service)
        mermaid.append(f'  {sid}>"{service}"]')
    mermaid.append("```")

    route_rows = [
        [r.method, f"`{r.path_pattern}`", f"`{r.file}`:{r.line}", r.framework]
        for r in sorted(facts.routes, key=lambda r: (r.path_pattern, r.method))[:60]
    ]

    return "\n".join([
        banner(facts),
        f"# {facts.name} — architecture",
        "",
        "Derived from dependency manifests, framework fingerprints, filesystem "
        "layout, and route extraction. Where this disagrees with the code, "
        "the code is right — this document is a map, not a specification.",
        "",
        "## Component map",
        "",
        *mermaid,
        "",
        "## Technology by layer",
        "",
        _table(["Layer", "Technologies"], layer_rows),
        "",
        "## Components by kind",
        "",
        _table(["Kind", "Components"],
               [[kind, ", ".join(names[:12])] for kind, names in comp_kinds.items()]),
        "",
        "## Entrypoints",
        "",
        "Where execution begins. Read these first when tracing a request.",
        "",
        *([f"- `{e}`" for e in facts.entrypoints[:25]] or ["_None detected._"]),
        "",
        "## HTTP / RPC surface",
        "",
        f"{len(facts.routes)} route(s) detected."
        + (" Showing the first 60." if len(facts.routes) > 60 else ""),
        "",
        _table(["Method", "Path", "Defined at", "Framework"], route_rows),
        "",
        "## Infrastructure",
        "",
        *([f"- `{p}`" for p in facts.infra[:30]] or ["_No infrastructure files detected._"]),
        "",
        "## CI workflows",
        "",
        *([f"- `{p}`" for p in facts.ci_workflows[:20]] or ["_No CI configuration detected._"]),
        "",
    ]) + "\n"


def render_repo_map(facts: RepoFacts, dir_stats: list[tuple[str, int, int, str]],
                    limit: int = 400) -> str:
    rows = [
        [f"`{path}/`", _fmt_int(files), _fmt_int(loc), langs]
        for path, files, loc, langs in dir_stats[:limit]
    ]
    return "\n".join([
        banner(facts),
        f"# {facts.name} — repository map",
        "",
        "Directories that contain indexed source, ordered by size. "
        "Generated, vendored, test-fixture, and ignored paths are excluded — "
        "if a directory is missing here, repo-ai deliberately skipped it.",
        "",
        f"Showing {min(len(dir_stats), limit)} of {len(dir_stats)} directories.",
        "",
        _table(["Directory", "Files", "LOC", "Languages"], rows),
        "",
        "## Where to look first",
        "",
        _table(["File", "Why", "Role"], [
            [f"`{item['path']}`", ", ".join(item["why"][:2]), item["role"]]
            for item in facts.important_files[:30]
        ]),
        "",
    ]) + "\n"


def render_dependencies(facts: RepoFacts, external_imports: list[tuple[str, int]]) -> str:
    by_manager: dict[str, list] = defaultdict(list)
    for dep in facts.dependencies:
        by_manager[dep.manager].append(dep)

    sections: list[str] = []
    for manager, deps in sorted(by_manager.items()):
        runtime = [d for d in deps if d.scope == "runtime"]
        dev = [d for d in deps if d.scope != "runtime"]
        sections.append(f"### {manager} ({len(deps)} declared)")
        sections.append("")
        sections.append(_table(["Package", "Version", "Scope", "Manifest"], [
            [f"`{d.name}`", d.version or "*", d.scope, f"`{d.manifest}`"]
            for d in (runtime[:45] + dev[:20])
        ]))
        sections.append("")

    return "\n".join([
        banner(facts),
        f"# {facts.name} — dependencies",
        "",
        _table(["Metric", "Value"], [
            ["Declared dependencies", str(len(facts.dependencies))],
            ["Package managers", ", ".join(facts.package_managers) or "none"],
            ["Distinct external imports in code", str(len(external_imports))],
        ]),
        "",
        "## Most-imported external packages",
        "",
        "Counted from actual `import`/`require` statements, not the manifest. "
        "A package high on this list is load-bearing; one in the manifest but "
        "absent here may be unused.",
        "",
        _table(["Package", "Files importing it"],
               [[f"`{name}`", str(count)] for name, count in external_imports[:40]]),
        "",
        "## Declared dependencies",
        "",
        *sections,
        "## External services",
        "",
        *([f"- {s}" for s in facts.external_services] or ["_None detected._"]),
        "",
    ]) + "\n"


def render_testing(facts: RepoFacts) -> str:
    from .testing import verification_plan
    signals = facts.conventions.get("test_coverage_signals", {})  # type: ignore[assignment]
    plan = verification_plan(facts.commands, facts.test_suites)
    rows = [
        [s.name, f"`{s.root}`", s.framework, s.kind, str(s.file_count),
         f"`{s.command}`" if s.command else "—"]
        for s in facts.test_suites
    ]
    untested = signals.get("directories_without_nearby_tests", []) if isinstance(signals, dict) else []

    def listed(items, empty):
        return [f"- `{c.command}` — {c.detail}" if c.detail else f"- `{c.command}`" for c in items] or [empty]
    how = listed(plan.tests, f"_No trustworthy test command: {plan.uncertain}. Check the CI workflow "
                             "and README; do not guess._")
    roots = sorted({f"`{s.root}/`" for s in facts.test_suites if s.root not in {".", ""}})
    return "\n".join([
        banner(facts),
        f"# {facts.name} — testing",
        "",
        "## How to verify a change",
        "",
        "Tests are the verification: run the tests relevant to the change, then the full suite. "
        "Static checks, builds and formatters complement them; none of them replaces running the "
        "tests. If the tests cannot run, say so rather than reporting the change as verified.",
        "",
        "### Tests",
        "",
        *how,
        *([f"- One test file or case: `{plan.targeted}`"] if plan.targeted else []),
        "",
        "A targeted run is a quick check while iterating. Before finishing, run the full suite: "
        "a change can pass its own tests and still break shared helpers or other modules.",
        "",
        "### Static analysis and type checks (complementary)",
        "",
        *listed(plan.static, "_None declared._"),
        "",
        "### Build (complementary)",
        "",
        *listed(plan.build, "_None declared._"),
        "",
        "### Formatters (rewrite files; run only when the project asks)",
        "",
        *listed(plan.format, "_None declared._"),
        *(["", "### Declared but withheld from agent instructions (review first)", "",
           *[f"- `{c}`" for c in plan.withheld]] if plan.withheld else []),
        "",
        "## Test suites",
        "",
        _table(["Suite", "Root", "Framework", "Kind", "Files", "Command"], rows),
        "",
        "## Balance signals",
        "",
        _table(["Signal", "Value"], [
            ["Source files", str(signals.get("source_files", "?"))],
            ["Test files", str(signals.get("test_files", "?"))],
            ["Test:source LOC ratio", str(signals.get("test_to_source_loc_ratio", "?"))],
        ]) if isinstance(signals, dict) else "",
        "",
        "These are shape heuristics, not coverage. Run the project's own "
        "coverage tool for real numbers.",
        "",
        "## Source directories no test refers to",
        "",
        "Heuristic: no test lives beside these, and no test file imports or names them. "
        "That is not a coverage measurement.",
        "",
        *([f"- `{d}/`" for d in untested[:15]] or ["_None found._"]),
        "",
        "## When adding code",
        "",
        "- Match the framework already used in the nearest test directory.",
        f"- Put new tests where this project keeps them ({', '.join(roots[:3])})." if roots else
        "- Put new tests where this project already keeps them.",
        "- Run the relevant tests, then the full suite, before declaring the task complete.",
        "",
    ]) + "\n"


