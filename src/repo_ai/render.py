def render_hotspots(facts: RepoFacts) -> str:
    rows = [
        [f"`{h.path}`", str(h.commits), _fmt_int(h.churn), str(h.authors),
         h.last_commit_iso[:10]]
        for h in facts.hotspots[:40]
    ]
    return "\n".join([
        banner(facts),
        f"# {facts.name} — change hotspots",
        "",
        "Files with the most commits in the analysed window. High churn "
        "usually means one of: active feature work, unstable design, or a "
        "file doing too many jobs. Use this to decide where a change is "
        "likely to ripple — not as a quality judgement.",
        "",
        _table(["File", "Commits", "Churn (lines)", "Authors", "Last touched"], rows),
        "",
        "## Recently changed",
        "",
        "Most recently committed files, newest first. Inspect history with "
        "`git log -p -- <path>` when a change needs context.",
        "",
        *([f"- `{p}`" for p in facts.recent_files[:20]] or ["_No git history._"]),
        "",
    ]) + "\n"


def render_security_notes(facts: RepoFacts, quarantined: list[str]) -> str:
    by_rule = Counter(h.rule for h in facts.secret_hits)
    rows = [
        [f"`{h.path}`", str(h.line) if h.line else "—", h.rule, h.severity, h.redacted]
        for h in sorted(facts.secret_hits, key=lambda h: (h.severity != "high", h.path))[:60]
    ]
    return "\n".join([
        banner(facts),
        f"# {facts.name} — secret scan",
        "",
        "**No secret values appear in this file.** Each finding shows a "
        "4-character prefix and a length only.",
        "",
        _table(["Metric", "Value"], [
            ["Candidate findings", str(len(facts.secret_hits))],
            ["Files quarantined (excluded from the index)", str(len(quarantined))],
            ["Distinct rules triggered", str(len(by_rule))],
        ]),
        "",
        "## Quarantined files",
        "",
        "These were excluded from the repo-ai index and from every agent hint "
        "repo-ai produces (and added to `.bobignore` when Bob is wired up). "
        "Agents can still open them if explicitly told to — do not paste or "
        "mention their contents in chat.",
        "",
        *([f"- `{p}`" for p in quarantined[:60]] or ["_None._"]),
        "",
        "## Findings",
        "",
        _table(["File", "Line", "Rule", "Severity", "Fingerprint"], rows),
        "",
        "## What to do",
        "",
        "1. Confirm each high-severity finding is a real credential.",
        "2. Rotate anything real. Assume a committed secret is compromised.",
        "3. Move it to a secret manager or an untracked `.env`.",
        "4. Re-run `repo-ai update` once resolved.",
        "",
        "False positives are possible; quarantine is reserved for key material "
        "and credential files, everything else is reported but stays indexed.",
        "",
    ]) + "\n"


