"""Markdown generation for the context directory (`.repo-ai/context/` or
`.bob/context/`).

Every generated file obeys three rules:

1. **Deterministic.** Same repo state -> same bytes. That makes the diff
   reviewable and keeps `git status` quiet between real changes.
2. **Front-loaded.** The first 20 lines carry the highest-value facts, because
   an agent that reads only the top of a file should still come away oriented.
3. **Bounded.** Every list has a cap. A 4,000-line REPOSITORY_MAP.md is a
   context-window hazard, not documentation.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import PurePosixPath

from .models import RepoFacts

def banner(facts: RepoFacts) -> str:
    notes = f"{facts.context_dir}/NOTES.md" if facts.context_dir else "NOTES.md"
    return (
        "<!-- Generated by repo-ai. Do not edit by hand: `repo-ai update` overwrites this file.\n"
        f"     Add durable, hand-written knowledge to {notes} instead. -->"
    )


def _fmt_int(value: int) -> str:
    return f"{value:,}"


def _bar(value: float, width: int = 18) -> str:
    filled = int(round(value * width))
    return "█" * filled + "·" * (width - filled)


def _table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_None found._"
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        cells = [str(c).replace("|", "\\|").replace("\n", " ")[:180] for c in row]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


