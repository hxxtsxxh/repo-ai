def directory_stats(files) -> list[tuple[str, int, int, str]]:
    """Aggregate indexed files by directory for the repository map."""
    agg: dict[str, list] = defaultdict(lambda: [0, 0, Counter()])
    for record in files:
        if record.role in {"generated", "fixture"}:
            continue
        directory = str(PurePosixPath(record.path).parent)
        directory = "." if directory == "." else directory
        entry = agg[directory]
        entry[0] += 1
        entry[1] += record.lines
        entry[2][record.language] += 1
    rows = [
        (path, count, loc, ", ".join(lang for lang, _ in langs.most_common(3)))
        for path, (count, loc, langs) in agg.items()
    ]
    rows.sort(key=lambda r: (-r[2], r[0]))
    return rows
